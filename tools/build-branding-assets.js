#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'assets/branding');
const background = '#232323';
const profiles = [
  [320, 568, 2], [375, 667, 2], [414, 736, 3], [375, 812, 3],
  [390, 844, 3], [393, 852, 3], [402, 874, 3], [414, 896, 2],
  [414, 896, 3], [428, 926, 3], [430, 932, 3], [440, 956, 3],
  [768, 1024, 2], [810, 1080, 2], [820, 1180, 2], [834, 1194, 2],
  [834, 1210, 2], [1024, 1366, 2], [1032, 1376, 2]
];

async function main() {
  fs.mkdirSync(directory, { recursive: true });
  const shell = [], records = [];
  const write = (label, bytes, extension, extra = {}) => {
    const hash = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    const relative = `assets/branding/${label}-${hash}.${extension}`;
    fs.writeFileSync(path.join(root, relative), bytes);
    shell.push('./' + relative);
    records.push({ path: relative, ...extra });
    return relative;
  };
  const logo = fs.readFileSync(path.join(root, 'logo-highres.png'));
  const icons = [];
  for (const size of [192, 512, 1024]) {
    const src = write(`icon-${size}`, await sharp(logo).resize(size, size, { withoutEnlargement: true }).png().toBuffer(), 'png', { kind: 'icon', width: size, height: size });
    icons.push({ src, sizes: `${size}x${size}`, type: 'image/png', purpose: 'any' });
  }
  for (const size of [512, 1024]) {
    const inner = Math.round(size * 0.72);
    const artwork = await sharp(logo).resize(inner, inner, { withoutEnlargement: true }).toBuffer();
    const bytes = await sharp({ create: { width: size, height: size, channels: 3, background } }).composite([{ input: artwork, gravity: 'centre' }]).png().toBuffer();
    const src = write(`icon-maskable-${size}`, bytes, 'png', { kind: 'maskable', width: size, height: size });
    icons.push({ src, sizes: `${size}x${size}`, type: 'image/png', purpose: 'maskable' });
  }
  const touchLinks = [];
  for (const size of [152, 167, 180]) {
    const src = write(`apple-touch-${size}`, await sharp(logo).resize(size, size).png().toBuffer(), 'png', { kind: 'touch', width: size, height: size });
    touchLinks.push(`  <link rel="apple-touch-icon" sizes="${size}x${size}" href="${src}">`);
  }
  const startupLinks = [];
  for (const [cssWidth, cssHeight, scale] of profiles) for (const orientation of ['portrait', 'landscape']) {
    const width = (orientation === 'portrait' ? cssWidth : cssHeight) * scale;
    const height = (orientation === 'portrait' ? cssHeight : cssWidth) * scale;
    const logoSize = Math.round(Math.min(cssWidth * 0.64, 220) * scale);
    const artwork = await sharp(logo).resize(logoSize, logoSize, { withoutEnlargement: true }).png().toBuffer();
    const bytes = await sharp({ create: { width, height, channels: 3, background } }).composite([{ input: artwork, gravity: 'centre' }])
      .png({ palette: true, colours: 256, dither: 0, compressionLevel: 9, effort: 10 }).toBuffer();
    const src = write(`startup-${width}x${height}`, bytes, 'png', { kind: 'startup', width, height, cssWidth, cssHeight, scale, orientation, logoSize });
    startupLinks.push(`  <link rel="apple-touch-startup-image" href="${src}" media="screen and (device-width: ${cssWidth}px) and (device-height: ${cssHeight}px) and (-webkit-device-pixel-ratio: ${scale}) and (orientation: ${orientation})">`);
  }
  const backgrounds = {};
  for (const orientation of ['landscape', 'portrait']) {
    const file = path.join(directory, `welcome-${orientation}-source.png`);
    const metadata = await sharp(file).metadata();
    backgrounds[orientation] = write(`welcome-${orientation}`, await sharp(file).webp({ quality: 92, effort: 6 }).toBuffer(), 'webp', { kind: 'welcome', width: metadata.width, height: metadata.height });
  }
  fs.writeFileSync(path.join(root, 'branding.css'), `/* Generated by tools/build-branding-assets.js. */\n:root { --welcome-image: url('${backgrounds.landscape}'); }\n@media (orientation: portrait) { :root { --welcome-image: url('${backgrounds.portrait}'); } }\n`);
  const manifestFile = path.join(root, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  manifest.id = './index.html';
  manifest.scope = './';
  manifest.background_color = background;
  manifest.icons = icons;
  fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
  const htmlFile = path.join(root, 'index.html');
  let html = fs.readFileSync(htmlFile, 'utf8');
  const tags = [`  <link rel="icon" href="${icons[0].src}" type="image/png" sizes="192x192">`, ...touchLinks, ...startupLinks];
  html = html.replace(/<!-- BRANDING_START -->[\s\S]*?<!-- BRANDING_END -->/, `<!-- BRANDING_START -->\n${tags.join('\n')}\n  <!-- BRANDING_END -->`);
  html = html.replace(/<!-- BOOT_LOGO_START -->[\s\S]*?<!-- BOOT_LOGO_END -->/, `<!-- BOOT_LOGO_START -->\n    <img src="${icons[2].src}" srcset="${icons[1].src} 512w, ${icons[2].src} 1024w" sizes="220px" width="220" height="220" alt="P274" decoding="sync">\n    <!-- BOOT_LOGO_END -->`);
  fs.writeFileSync(htmlFile, html);
  fs.writeFileSync(path.join(directory, 'asset-index.json'), JSON.stringify({ source: 'logo-highres.png', shell, records }, null, 2) + '\n');
  console.log(`Branding: ${icons.length} manifest icons, ${touchLinks.length} touch icons, ${startupLinks.length} native launch images, 2 native-resolution welcome backgrounds.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
